# Pixel-art sprites for the Drive game -> sketch-ota/puck_ota/game_sprites.h
# LVGL 8 LV_IMG_CF_TRUE_COLOR_CHROMA_KEYED (RGB565 little-endian, chroma key = pure green), pre-scaled x3.
from PIL import Image
S = 3
PAL = {'.': None, 'K': (24, 24, 28), 'W': (170, 220, 255), 'R': (255, 70, 60), 'B': (40, 110, 230), 'C': (220, 50, 50),
       'Y': (245, 200, 40), 'O': (255, 140, 30), 'w': (250, 250, 250), 'G': (90, 90, 96), 'L': (255, 240, 170)}
CAR = [
 "..KKKKKK..",
 ".KXXXXXXK.",
 "KKXWWWWXKK",
 "KKXWWWWXKK",
 ".KXXXXXXK.",
 ".KXXXXXXK.",
 ".KXXXXXXK.",
 "KKXXXXXXKK",
 "KKXXXXXXKK",
 ".KXWWWWXK.",
 ".KXXXXXXK.",
 ".KXXXXXXK.",
 "KKXXXXXXKK",
 "KKXXXXXXKK",
 ".KXRXXRXK.",
 "..KKKKKK..",
]
CONE = [
 "....OO....",
 "....OO....",
 "...OwwO...",
 "...OOOO...",
 "..OOOOOO..",
 "..wwwwww..",
 ".OOOOOOOO.",
 "KKKKKKKKKK",
]
def car(body, down=False, head=False):
    rows = [r.replace('X', body) for r in CAR]
    if head: rows[1] = rows[1].replace(body, 'L', 1)[::-1].replace(body, 'L', 1)[::-1]
    return rows[::-1] if down else rows
SPR = {'spr_player': car('B'), 'spr_car_red': car('C', down=True), 'spr_car_yel': car('Y', down=True), 'spr_cone': CONE}
out = ['// Generated by tools_sprites.py - Drive game pixel art (own art)', '#pragma once', '#include "lvgl.h"']
prev = Image.new('RGB', (4 * 40, 60), (90, 160, 80))
for k, (name, rows) in enumerate(SPR.items()):
    h, w = len(rows), len(rows[0])
    data = bytearray(); im = Image.new('RGB', (w * S, h * S), (0, 255, 0))
    for y in range(h * S):
        for x in range(w * S):
            c = PAL[rows[y // S][x // S]] or (0, 255, 0)
            v = ((c[0] >> 3) << 11) | ((c[1] >> 2) << 5) | (c[2] >> 3)
            data += bytes([v & 255, v >> 8]); im.putpixel((x, y), c)
    out.append(f'static const uint8_t {name}_map[] = {{' + ','.join(map(str, data)) + '};')
    out.append(f'static const lv_img_dsc_t {name} = {{ {{ LV_IMG_CF_TRUE_COLOR_CHROMA_KEYED, 0, 0, {w * S}, {h * S} }}, sizeof({name}_map), {name}_map }};')
    m = im.copy(); px = m.load()
    for y in range(m.height):
        for x in range(m.width):
            if px[x, y] == (0, 255, 0): px[x, y] = (90, 160, 80)
    prev.paste(m, (k * 40 + 5, 6))
open('sketch-ota/puck_ota/game_sprites.h', 'w').write('\n'.join(out) + '\n')
prev.resize((prev.width * 3, prev.height * 3), Image.NEAREST).save('/workspace/sprites_preview.png')
print('ok')
