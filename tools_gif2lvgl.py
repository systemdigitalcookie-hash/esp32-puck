# Convert headset_src.gif -> sketch-ota/puck_ota/headset_img.h (LVGL 8 LV_IMG_CF_INDEXED_2BIT frames)
import sys
from PIL import Image, ImageSequence
SZ = int(sys.argv[1]) if len(sys.argv) > 1 else 150
STEP = int(sys.argv[2]) if len(sys.argv) > 2 else 1
PAL = [(255, 255, 255), (0, 0, 0), (11, 136, 234), (221, 221, 221)]   # white, black, blue, light grey
def idx(p):
    r, g, b = p
    if b > r + 60 and b > 120: return 2                       # blue
    lum = 0.3 * r + 0.59 * g + 0.11 * b
    if lum < 150: return 1                                     # black (biased: keeps thin lines solid)
    if lum < 238 and abs(r - g) < 20 and abs(g - b) < 20: return 3
    return 0
im = Image.open('headset_src.gif')
frames = []
for i, f in enumerate(ImageSequence.Iterator(im)):
    if i % STEP: continue
    a = f.convert('RGBA'); bg = Image.new('RGBA', a.size, (255, 255, 255, 255)); bg.alpha_composite(a)
    frames.append(bg.convert('RGB').resize((SZ, SZ), Image.LANCZOS))
stride = (SZ + 3) // 4
out = ['// Generated by tools_gif2lvgl.py from headset_src.gif - personal asset (gitignored)', '#pragma once', '#include "lvgl.h"',
       f'#define HEADSET_W {SZ}', f'#define HEADSET_FRAMES {len(frames)}', f'#define HEADSET_MS {100 * STEP}']
prev = []
for n, fr in enumerate(frames):
    px = fr.load(); data = bytearray()
    for (r, g, b) in PAL: data += bytes([b, g, r, 255])
    q = Image.new('RGB', (SZ, SZ))
    for y in range(SZ):
        row = bytearray(stride)
        for x in range(SZ):
            k = idx(px[x, y]); row[x >> 2] |= k << (6 - 2 * (x & 3)); q.putpixel((x, y), PAL[k])
        data += row
    prev.append(q)
    out.append(f'static const uint8_t hs_f{n}[{len(data)}] = {{' + ','.join(str(v) for v in data) + '};')
out.append('static const lv_img_dsc_t headset_frames[HEADSET_FRAMES] = {')
for n in range(len(frames)):
    out.append(f'  {{ {{ LV_IMG_CF_INDEXED_2BIT, 0, 0, {SZ}, {SZ} }}, sizeof(hs_f{n}), hs_f{n} }},')
out.append('};')
open('sketch-ota/puck_ota/headset_img.h', 'w').write('\n'.join(out) + '\n')
sheet = Image.new('RGB', (6 * SZ, ((len(prev) + 5) // 6) * SZ), 'white')
for i, q in enumerate(prev): sheet.paste(q, ((i % 6) * SZ, (i // 6) * SZ))
sheet.save('headset_preview.png')
print(len(frames), 'frames,', len(frames) * (16 + stride * SZ), 'bytes')
